const jwt = require('jsonwebtoken');
const User = require('../models/User');

/**
 * protect — verify a JWT from the Authorization header and attach
 * the authenticated user to req.user. Returns 401 on missing/invalid token.
 */
const protect = async (req, res, next) => {
  let token;

  if (req.headers.authorization && req.headers.authorization.startsWith('Bearer ')) {
    token = req.headers.authorization.split(' ')[1];
  }

  if (!token) {
    return res.status(401).json({
      success: false,
      message: 'Not authorized, no token provided',
    });
  }

  try {
    const decoded = jwt.verify(token, process.env.JWT_SECRET);
    // select('+password') is not needed here; we just need the user identity/role.
    const user = await User.findById(decoded.id).select('-password');
    if (!user) {
      return res.status(401).json({
        success: false,
        message: 'Not authorized, user no longer exists',
      });
    }
    req.user = user;
    next();
  } catch (error) {
    return res.status(401).json({
      success: false,
      message: 'Not authorized, token failed or expired',
    });
  }
};

/**
 * admin — restrict a route to authenticated administrators.
 * Must be used AFTER protect so req.user is available.
 */
const admin = (req, res, next) => {
  if (req.user && req.user.role === 'admin') {
    return next();
  }
  return res.status(403).json({
    success: false,
    message: 'Forbidden, admin access required',
  });
};

module.exports = { protect, admin };
